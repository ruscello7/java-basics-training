public class Methods {

    static int maior (int a, int b) {
        if (a > b) {
            return a; }
        else {
                return b;
            }
        }

    public static void main(String[] args) {
        System.out.println(maior(10, 20));
        System.out.println(maior(15, 25));
        System.out.println(maior(5, 10));

    }

    }